//! `src/ai_data.cyr`: Rust's `char::is_alphanumeric` as a baked range table (port plan §3 M2).
//!
//! `suggest_redactions` trims an email token's ends with `!c.is_alphanumeric()`, which is Unicode's Alphabetic
//! property (letters, Nl, and Other_Alphabetic marks and symbols) plus Numeric (Nd, Nl, No). The stdlib's
//! `lib/unicode/categories` gives general categories only, so the table comes from Rust itself: exact for the Unicode
//! version the oracle's compiler carries, recorded in the header.

use crate::SrcOut;

pub fn emit(out: &mut SrcOut) {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    let mut start: Option<u32> = None;
    for cp in 0u32..=0x11_0000 {
        let alnum = char::from_u32(cp).is_some_and(char::is_alphanumeric);
        match (alnum, start) {
            (true, None) => start = Some(cp),
            (false, Some(s)) => {
                ranges.push((s, cp - 1));
                start = None;
            }
            _ => {}
        }
    }
    let (maj, min, upd) = char::UNICODE_VERSION;
    let mut s = String::new();
    s.push_str("# ai_data.cyr — GENERATED by scripts/oracle (src/t_ai.rs). Do not edit: regenerate with\n");
    s.push_str("#   cargo run --release --locked --manifest-path scripts/oracle/Cargo.toml\n");
    s.push_str(&format!(
        "# Rust's char::is_alphanumeric (Unicode {maj}.{min}.{upd}, rustc 1.100.0) as {} inclusive code-point ranges,\n",
        ranges.len()
    ));
    s.push_str("# sorted, for ai.cyr's binary search. Surrogates are not characters and are never in a range.\n\n");
    s.push_str(&format!("var _SL_ALNUM_N = {};\n\n", ranges.len()));
    for (name, pick) in [("_SL_ALNUM_LO", 0usize), ("_SL_ALNUM_HI", 1usize)] {
        s.push_str(&format!("var {name}: u32[{}] = {{\n", ranges.len()));
        for chunk in ranges.chunks(8) {
            let row: Vec<String> = chunk.iter().map(|r| format!("0x{:X}", if pick == 0 { r.0 } else { r.1 })).collect();
            s.push_str(&format!("    {},\n", row.join(", ")));
        }
        s.push_str("};\n\n");
    }
    s.pop();
    out.insert("src/ai_data.cyr".to_string(), s.into_bytes());
}

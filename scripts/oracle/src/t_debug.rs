//! `src/debug_data.cyr`: the non-ASCII characters Rust's `Debug` for `str` writes as `\u{…}` (port plan §3 M5).
//!
//! `{:?}` on a str escapes a character that is not printable or is a grapheme extender (core's `is_printable` and
//! `is_grapheme_extended` tables). selah prints Rust's Debug of user strings in error texts (an agent id, an endpoint,
//! an annotation kind), so the set comes from Rust itself, measured through `format!("{:?}")` and recorded with its
//! Unicode version. The set does not depend on a character's position in the string (measured at 2026-11-14).

use crate::SrcOut;

pub fn emit(out: &mut SrcOut) {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    let mut start: Option<u32> = None;
    for cp in 0x80u32..=0x11_0000 {
        let esc = char::from_u32(cp).is_some_and(|c| format!("{:?}", c.to_string()) != format!("\"{c}\""));
        match (esc, start) {
            (true, None) => start = Some(cp),
            (false, Some(s)) => {
                ranges.push((s, cp - 1));
                start = None;
            }
            _ => {}
        }
    }
    let (maj, min, upd) = char::UNICODE_VERSION;
    let mut s = String::new();
    s.push_str("# debug_data.cyr — GENERATED by scripts/oracle (src/t_debug.rs). Do not edit: regenerate with\n");
    s.push_str("#   cargo run --release --locked --manifest-path scripts/oracle/Cargo.toml\n");
    s.push_str(&format!(
        "# The non-ASCII characters Rust's Debug for str escapes as \\u{{…}} (Unicode {maj}.{min}.{upd}, rustc 1.100.0),\n"
    ));
    s.push_str(&format!(
        "# as {} inclusive code-point ranges, sorted, for core.cyr's binary search. Surrogates are never in a range.\n\n",
        ranges.len()
    ));
    s.push_str(&format!("var _SL_DBGESC_N = {};\n\n", ranges.len()));
    for (name, pick) in [("_SL_DBGESC_LO", 0usize), ("_SL_DBGESC_HI", 1usize)] {
        s.push_str(&format!("var {name}: u32[{}] = {{\n", ranges.len()));
        for chunk in ranges.chunks(8) {
            let row: Vec<String> = chunk.iter().map(|r| format!("0x{:X}", if pick == 0 { r.0 } else { r.1 })).collect();
            s.push_str(&format!("    {},\n", row.join(", ")));
        }
        s.push_str("};\n\n");
    }
    s.pop();
    out.insert("src/debug_data.cyr".to_string(), s.into_bytes());
}
